"""Select published liver-chip evidence and validate its experiment integration.

Imported results remain external evidence. Mapping them to a fixture compartment
is an application association, not evidence that the fixture produced the data.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

from forma_core.workspaces.projects.models import HardwareIntermediateRepresentation

from .benchmark import evaluate_biological_scenario
from .ewart_liverchip import EwartDataset, MODEL_FIELDS, load_dataset, summarize_observations
from .models import BiologicalExperiment

ENDPOINTS = {
    "albumin": ("Albumin", "function", "percent_of_control"),
    "alt": ("ALT", "injury", "ng/day/1e6_hepatocytes"),
    "morphology": ("Morphology", "imaging", "morphology_score"),
}


def build_evidence_experiment(
    dataset: EwartDataset,
    compound: str,
    template: BiologicalExperiment,
    compartment_id: str = "hepatic_compartment",
) -> BiologicalExperiment:
    """Build a fresh source-evidence scenario using only the template's compartments.

    Selection matches a published name or ID exactly, ignoring case and outer
    whitespace. Existing template exposures and labels are never reassigned to
    the selected compound. Unavailable exposure duration and donor IDs remain
    unspecified; dose metadata belongs to each observation, not a fake protocol.
    """
    query = compound.strip().casefold()
    selected = next((c for c in dataset.compounds if query in {c.id.casefold(), c.name.casefold()}), None)
    if selected is None:
        raise ValueError(f"Unknown compound {compound!r}; choose a compound from the Ewart dataset.")
    if compartment_id not in {c.id for c in template.compartments}:
        raise ValueError(f"Unknown template compartment {compartment_id!r}.")
    observations = [o for o in dataset.observations if o.compound_id == selected.id]
    prefix = f"ewart_{selected.id}"
    return BiologicalExperiment.model_validate({
        "id": prefix, "name": f"{selected.name}: published Liver-Chip evidence",
        "organ_model": template.organ_model,
        "purpose": "Inspect external Ewart 2022 evidence associated with a Forma liver-chip fixture; no new toxicity prediction.",
        "compartments": [c.model_dump() for c in template.compartments],
        "exposures": [], "controls": [],
        "endpoints": [{"id": f"ewart_{key}", "name": name, "measurement_type": kind, "unit": unit,
            "dataset_ref_ids": ["ewart_supplement8"],
            "description": "External source endpoint; values were not measured on this Forma fixture."}
            for key, (name, kind, unit) in ENDPOINTS.items()],
        "sampling_points": [],
        "datasets": [{"id": f"ewart_{source.id}", "name": f"Ewart 2022 {source.id}",
            "kind": "assay" if source.id == "supplement8" else "literature",
            "uri": source.uri, "version": dataset.version, "license": dataset.license,
            "citation": dataset.attribution, "sha256": source.sha256,
            "notes": "External published source; derived dataset changes: " + " ".join(dataset.changes)}
            for source in dataset.sources],
        "observations": [{"id": f"{prefix}_{o.endpoint}_{o.source_row}",
            "endpoint_id": f"ewart_{o.endpoint}", "compartment_id": compartment_id,
            "compound_identifier": selected.id, "dose_value": o.dose_cmax_multiple,
            "dose_unit": "human_cmax_multiple", "time_h": o.day * 24,
            "numeric_value": o.value, "unit": o.unit, "dataset_ref_id": "ewart_supplement8",
            "source_record_id": f"{o.source_sheet}:row{o.source_row}",
            "measurement_status": "missing" if o.value is None else "observed",
            "missing_reason": "Source workbook reports no numerical result." if o.value is None else None,
            "source_missing_marker": o.source_missing_marker,
            "notes": "Source day 3 encoded as nominal 72 h; donor/chip IDs and exposure duration are unavailable. External evidence associated with this compartment, not generated by this fixture."}
            for o in observations],
        "reference_outcomes": [{"id": f"{prefix}_severity", "subject": selected.name,
            "outcome_type": "severity", "value": str(selected.garside_rank),
            "dataset_ref_id": "ewart_article", "source_record_id": selected.reference_locator,
            "notes": "Published Garside rank; ranks 1–3 are reference positives. " + (selected.identity_note or "")}],
        "limitations": [*dataset.limitations,
            "Fixture mapping is an application association, not experimental equivalence or a claim that Forma produced these measurements.",
            "Source day 3 is represented as nominal 72 h, not a reconstructed exposure timeline.",
            "Template exposures, controls, sampling plans and reference labels are excluded; no experimental protocol is inferred."]})


def build_evidence_report(
    dataset: EwartDataset,
    experiment: BiologicalExperiment,
    project: HardwareIntermediateRepresentation,
) -> dict[str, Any]:
    """Report selected-compound evidence separately from structural validation."""
    compound_name = experiment.reference_outcomes[0].subject
    compound = next(c for c in dataset.compounds if c.name == compound_name)
    rows = experiment.observations
    measured = sum(o.measurement_status == "observed" for o in rows)
    missing = len(rows) - measured
    status = "unavailable" if not rows else (
        "all_missing" if measured == 0 else "partial" if missing else "complete")
    return {
        "compound": {"id": compound.id, "name": compound.name, "identity_note": compound.identity_note},
        "evidence": {"status": status, "source_rows": len(rows), "measured_values": measured,
            "missing_values": missing, "availability_scope": "Supplementary Data 8 response rows for this compound only",
            "reason": "No response rows supplied for this compound in Supplementary Data 8." if not rows else None,
            "dose_response_summary": [g for g in summarize_observations(dataset) if g["compound_id"] == compound.id],
            "published_margins": {model: getattr(compound, model).raw for model in MODEL_FIELDS},
            "margin_locator": compound.margin_locator,
            "reference_label": compound.reference_label, "reference_locator": compound.reference_locator},
        "validation": evaluate_biological_scenario(experiment, project),
        "experiment": experiment.model_dump(mode="json"),
        "claims": {"external_evidence_only": True, "fixture_generated_measurements": False,
            "toxicity_prediction": False, "clinical_safety_assessment": False},
    }


def main(argv: list[str] | None = None) -> int:
    """Export a selected compound's experiment and report; reject unknown selections."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dataset", type=Path)
    parser.add_argument("--compound", required=True)
    parser.add_argument("--template", required=True, type=Path)
    parser.add_argument("--project", required=True, type=Path)
    parser.add_argument("--compartment", default="hepatic_compartment")
    parser.add_argument("--output", type=Path, help="JSON evidence report including experiment and validation.")
    parser.add_argument("--experiment-output", type=Path, help="Standalone BiologicalExperiment JSON.")
    args = parser.parse_args(argv)
    inputs = {p.resolve() for p in (args.dataset, args.template, args.project)}
    outputs = [p.resolve() for p in (args.output, args.experiment_output) if p is not None]
    if inputs.intersection(outputs) or len(set(outputs)) != len(outputs):
        parser.error("Output paths must be distinct and must not overwrite input files.")
    try:
        dataset = load_dataset(args.dataset)
        template = BiologicalExperiment.model_validate_json(args.template.read_text(encoding="utf-8"))
        project = HardwareIntermediateRepresentation.model_validate_json(args.project.read_text(encoding="utf-8"))
        experiment = build_evidence_experiment(dataset, args.compound, template, args.compartment)
        report = build_evidence_report(dataset, experiment, project)
    except (ValueError, OSError) as exc:
        parser.error(str(exc))
    report["derived_dataset_sha256"] = hashlib.sha256(args.dataset.read_bytes()).hexdigest()
    payload = json.dumps(report, indent=2, sort_keys=True, allow_nan=False) + "\n"
    if args.output:
        args.output.write_text(payload, encoding="utf-8")
    if args.experiment_output:
        args.experiment_output.write_text(json.dumps(experiment.model_dump(mode="json"), indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")
    print(payload, end="")
    return 0 if report["validation"]["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
